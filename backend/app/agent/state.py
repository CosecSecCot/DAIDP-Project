from typing import NotRequired, TypedDict


class IntakeState(TypedDict):
    # Required on every run; the security and specialist nodes process this message.
    user_message: str

    # Set by the security node to record the selected handler.
    intent: NotRequired[str]

    # Required transcript; intake uses it to understand answers across turns.
    conversation: list[dict[str, str]]

    # Optional extracted context from documents attached to this conversation.
    patient_history: NotRequired[str]

    # Optional IDs of documents attached to this conversation.
    document_ids: NotRequired[list[str]]
    
    # Facts extracted from the conversation by intake.
    intake_facts: NotRequired[dict[str, str]]
    
    # Reserved for reporting which intake details are missing; currently unused.
    missing_fields: NotRequired[list[str]]
    
    # Number of intake follow-up questions asked so far.
    followup_rounds: NotRequired[int]
    
    # Current flow state, such as needs_more_information or awaiting_slot_choice.
    status: NotRequired[str]
    
    # The next question to show when intake needs more information.
    followup_question: NotRequired[str]

    # Reserved intake completion flag; currently unused.
    intake_sufficient: NotRequired[bool]

    # Active doctors loaded by the API for matching recommendations.
    doctor_directory: NotRequired[list[dict[str, str]]]

    # Ready, attached documents provided to the document explanation node.
    document_catalog: NotRequired[list[dict[str, str]]]

    # Currently available appointment slots loaded by the API.
    available_slots: NotRequired[list[dict[str, str]]]

    # Slot IDs shown to the user; booking is limited to these choices.
    offered_slot_ids: NotRequired[list[str]]

    # General reply produced by the active graph node.
    assistant_reply: NotRequired[str]

    # Document IDs cited by the document explanation node.
    source_documents: NotRequired[list[str]]

    # Short summary of the health concern extracted or generated by intake.
    intake_summary: NotRequired[str]

    # Model-estimated urgency returned with preliminary guidance.
    urgency: NotRequired[str]

    # Conservative preliminary steps returned by intake.
    preliminary_steps: NotRequired[str]

    # Safety disclaimer shown with preliminary medical guidance.
    guidance_disclaimer: NotRequired[str]

    # Specialties suggested for the reported concern.
    specialties: NotRequired[list[str]]

    # Whether intake recommends assessment by a doctor.
    doctor_recommended: NotRequired[bool]

    # Explanation for recommending a doctor.
    doctor_reason: NotRequired[str]

    # Tracks an explicit doctor or appointment request through intake.
    doctor_requested: NotRequired[bool]

    # Indicates whether preliminary guidance has been generated in this flow.
    has_guidance: NotRequired[bool]

    # Doctors matched to the concern or shown on direct request.
    doctor_recommendations: NotRequired[list[dict[str, str]]]

    # Handler selected by security for this run.
    next_action: NotRequired[str]

    # Set when security rejects the request.
    security_blocked: NotRequired[bool]

    # Short explanation of the security node's decision.
    security_reason: NotRequired[str]

    # Intake's next graph step: doctors or finish.
    next_flow: NotRequired[str]

